-- H2 本地文件数据库初始化脚本。连锁眼镜店：验光与加工底账。
-- 约定：全库禁止物理删除；作废/冲销均以状态位体现并写操作日志；
-- 每张业务表带操作人、请求号、业务时间、版本号；重复提交由唯一约束兜底。

-- ---------------------------------------------------------------------------
-- 骨架版本表
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_evops_schema_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_no VARCHAR(32) NOT NULL,
    description VARCHAR(255) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_evops_schema_version UNIQUE (version_no)
);

-- ---------------------------------------------------------------------------
-- 镜片基础信息
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_lens (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lens_code       VARCHAR(64)  NOT NULL,
    lens_name       VARCHAR(128) NOT NULL,
    brand           VARCHAR(64),
    lens_type       VARCHAR(32),
    refractive_index VARCHAR(16),
    price           DECIMAL(10, 2),
    lens_status     VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',   -- ACTIVE / DISCARDED
    remark          VARCHAR(255),
    created_by      BIGINT,
    created_time    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by      BIGINT,
    updated_time    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    request_no      VARCHAR(64),
    biz_time        TIMESTAMP,
    version_no      BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uk_lens_code UNIQUE (lens_code)
);

CREATE TABLE IF NOT EXISTS t_lens_oper_log (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lens_id      BIGINT       NOT NULL,
    oper_type    VARCHAR(16)  NOT NULL,   -- CREATE / UPDATE / DISCARD / RESTORE
    oper_remark  VARCHAR(255),
    oper_by      BIGINT,
    request_no   VARCHAR(64),
    biz_time     TIMESTAMP,
    version_no   BIGINT
);

-- ---------------------------------------------------------------------------
-- 加工单主表
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_process_order (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no       VARCHAR(64)  NOT NULL,
    customer_name  VARCHAR(64),
    customer_phone VARCHAR(32),
    store_code     VARCHAR(32),
    lens_id        BIGINT       NOT NULL,
    order_status   VARCHAR(16)  NOT NULL DEFAULT 'CREATED',
                    -- CREATED 已建档 / PROCESSING 加工中 / READY 待取镜 / PICKED_UP 已取镜 / CANCELLED 已冲销
    remark         VARCHAR(255),
    created_by     BIGINT,
    created_time   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by     BIGINT,
    updated_time   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    request_no     VARCHAR(64),
    biz_time       TIMESTAMP,
    version_no     BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uk_order_no       UNIQUE (order_no),
    CONSTRAINT uk_order_request  UNIQUE (request_no)   -- 库层兜底重复提交
);

-- ---------------------------------------------------------------------------
-- 加工单处方明细（左右眼各一行）
-- 编辑加工单时不物理删除旧行：旧行置 VOID，新行重新插入，与主表同一事务。
-- active_eye 为生成列：仅 ACTIVE 行参与唯一约束，保证每只眼最多一条有效处方。
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_process_order_rx (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      BIGINT      NOT NULL,
    eye           VARCHAR(8)  NOT NULL,                  -- L / R
    sphere        DECIMAL(5, 2),                         -- 球镜 S
    cylinder      DECIMAL(5, 2),                         -- 柱镜 C（散光）
    axis          INT,                                   -- 轴位 1~180
    add_power     DECIMAL(4, 2),                         -- 下加光 ADD
    pd            INT,                                   -- 瞳距 mm
    record_status VARCHAR(8)  NOT NULL DEFAULT 'ACTIVE', -- ACTIVE / VOID
    active_eye    VARCHAR(8) GENERATED ALWAYS AS (CASE WHEN record_status = 'ACTIVE' THEN eye ELSE NULL END),
    created_by    BIGINT,
    created_time  TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by    BIGINT,
    updated_time  TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    request_no    VARCHAR(64),
    biz_time      TIMESTAMP,
    version_no    BIGINT      NOT NULL DEFAULT 0,
    CONSTRAINT uk_order_rx_active UNIQUE (order_id, active_eye)
);

