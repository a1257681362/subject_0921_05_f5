-- ---------------------------------------------------------------------------
-- 加工单文本敏感词扫描留痕（只追加）
-- 每次扫描（含无命中的 PASS）按加工单按字段留一行：命中明细、处置动作、词库版本，
-- 供别组取数与"以加工单为准"的反向核对（RECHECK 行由核对接口写入）。
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_sensitive_scan_log (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     BIGINT,                   -- 被拦截（BLOCK）时加工单未建档，可空
    order_no     VARCHAR(64),
    field_name   VARCHAR(32)  NOT NULL,    -- customerName / remark
    action       VARCHAR(16)  NOT NULL,    -- PASS / MASK / BLOCK / RECHECK
    hit_count    INT          NOT NULL DEFAULT 0,
    hit_detail   VARCHAR(4000),            -- JSON：[{"word","level","start","end"}]，原文坐标；超长截断（hit_count 仍准确）
    dict_version VARCHAR(64)  NOT NULL,    -- 词库版本（内容 MD5 短串）
    oper_type    VARCHAR(16)  NOT NULL,    -- CREATE / UPDATE / RECHECK
    created_by   BIGINT,
    created_time TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by   BIGINT,
    updated_time TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    request_no   VARCHAR(64),
    biz_time     TIMESTAMP,
    version_no   BIGINT       NOT NULL DEFAULT 0
);

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('lens-order-1', '镜片基础信息与加工单（验光/取镜流转/检索）底账');

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('sensitive-1', '加工单文本敏感词扫描留痕与反向核对');

-- ---------------------------------------------------------------------------
-- 批量后台任务（加工单批量处理，如敏感词全量反向核对异步化）
-- 任务在后台线程执行，不占请求线程；凭 job_no 查进度（progress_pct 按 5% 一档）、
-- 协作式可取消、失败/取消后可断点重跑（已成功的明细不重复处理）。
-- 说明：本表是全库"禁止物理删除"约定的唯一例外——任务记录属运维临时数据，
-- expire_time 到期（默认完成后 21 天）由定时任务物理清理；业务底账
-- （RECHECK 扫描留痕等）仍只追加，不受影响。
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_batch_job (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_no           VARCHAR(64)  NOT NULL,                -- 任务号，凭此查进度/取消/重跑
    job_type         VARCHAR(32)  NOT NULL,                -- RECHECK（敏感词反向核对）
    job_status       VARCHAR(16)  NOT NULL DEFAULT 'PENDING',
                     -- PENDING 待执行 / RUNNING 执行中 / SUCCEEDED 成功 / FAILED 失败（可重跑）/ CANCELLED 已取消（可重跑）
    total_count      INT          NOT NULL DEFAULT 0,      -- 快照总单数
    processed_count  INT          NOT NULL DEFAULT 0,      -- 已处理单数（成功+失败）
    success_count    INT          NOT NULL DEFAULT 0,
    failed_count     INT          NOT NULL DEFAULT 0,
    progress_pct     INT          NOT NULL DEFAULT 0,      -- 进度百分比，恒为 5 的整数倍 0~100
    cancel_requested CHAR(1)      NOT NULL DEFAULT 'N',    -- Y：协作式取消请求（单据边界生效）
    params_json      VARCHAR(1000),                        -- 任务参数 JSON（如 storeCode）
    result_json      CLOB,                                 -- 终态报告 JSON（成功/失败均写，含失败单明细）
    error_message    VARCHAR(1000),                        -- 任务级错误（如整体异常）
    started_time     TIMESTAMP,
    finished_time    TIMESTAMP,
    expire_time      TIMESTAMP,                            -- 记录过期时间（finished_time + 保留天数），到期物理清理
    created_by       BIGINT,
    created_time     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by       BIGINT,
    updated_time     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    request_no       VARCHAR(64),
    biz_time         TIMESTAMP,
    version_no       BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uk_batch_job_no      UNIQUE (job_no),
    CONSTRAINT uk_batch_job_request UNIQUE (request_no)    -- 库层兜底重复提交
);

-- 任务明细：每单一行，断点重跑的依据（uk 兜底；重跑复用原行，SUCCESS 跳过）
CREATE TABLE IF NOT EXISTS t_batch_job_item (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id       BIGINT       NOT NULL,
    order_id     BIGINT       NOT NULL,
    order_no     VARCHAR(64)  NOT NULL,
    item_status  VARCHAR(16)  NOT NULL,                    -- SUCCESS / FAILED
    fail_reason  VARCHAR(1000),
    result_json  CLOB,                                     -- 该单核对结果 JSON（neverScanned/字段差异），供断点后续跑汇总
    created_by   BIGINT,
    created_time TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by   BIGINT,
    updated_time TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    request_no   VARCHAR(64),
    biz_time     TIMESTAMP,
    version_no   BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uk_batch_job_item UNIQUE (job_id, order_id)
);

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('batch-job-1', '加工单批量处理后台任务（进度/取消/断点重跑/21天保留）');

-- ---------------------------------------------------------------------------
-- 门店额度三段式（预占-确认-释放）
-- 约定：每门店一个额度账户（store_code 唯一），金额制；
-- 预占 40 分钟内有效（服务器时钟，可配），超时由定时扫描自动归还；
-- 实扣必须以有效预占为前提且与预占等额；预占/实扣/释放/超时/调额全部写
-- 只追加流水 t_quota_flow；每日定时"日结对平"：账户占用=未结预占合计、
-- 账户实扣=实扣流水合计、每笔实扣必有预占来源、无超时未还预占。
-- 余额变动走条件更新（占用+实扣+本次 <= 总额），并发下不会超占。
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_quota_account (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_code      VARCHAR(32)   NOT NULL,                -- 门店编码，一户一码
    total_quota     DECIMAL(14,2) NOT NULL DEFAULT 0,      -- 总额度
    reserved_amount DECIMAL(14,2) NOT NULL DEFAULT 0,      -- 占用中（预占未确认/未释放）
    used_amount     DECIMAL(14,2) NOT NULL DEFAULT 0,      -- 已实扣
    remark          VARCHAR(255),
    created_by      BIGINT,
    created_time    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by      BIGINT,
    updated_time    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    request_no      VARCHAR(64),
    biz_time        TIMESTAMP,
    version_no      BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uk_quota_account_store UNIQUE (store_code)
);

-- 预占单：HELD 占用中 / CONFIRMED 已实扣 / RELEASED 已手工释放 / EXPIRED 超时归还
CREATE TABLE IF NOT EXISTS t_quota_hold (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hold_no        VARCHAR(64)   NOT NULL,                 -- 预占单号，服务端生成
    account_id     BIGINT        NOT NULL,
    store_code     VARCHAR(32)   NOT NULL,                 -- 冗余门店编码，便于检索
    amount         DECIMAL(14,2) NOT NULL,
    hold_status    VARCHAR(16)   NOT NULL DEFAULT 'HELD',
    biz_type       VARCHAR(32),                            -- 关联业务类型（如 PROCESS_ORDER），可空
    biz_no         VARCHAR(64),                            -- 关联业务单号（如加工单号），可空
    expire_time    TIMESTAMP     NOT NULL,                 -- 占用截止（预占起 40 分钟，服务器时钟）
    confirmed_time TIMESTAMP,
    released_time  TIMESTAMP,
    release_reason VARCHAR(255),                           -- 手工释放备注 / 超时自动归还
    remark         VARCHAR(255),
    created_by     BIGINT,
    created_time   TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by     BIGINT,
    updated_time   TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    request_no     VARCHAR(64),
    biz_time       TIMESTAMP,
    version_no     BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT uk_quota_hold_no      UNIQUE (hold_no),
    CONSTRAINT uk_quota_hold_request UNIQUE (request_no)   -- 库层兜底重复提交
);

-- 超时扫描按（状态, 到期时间）取数
CREATE INDEX IF NOT EXISTS idx_quota_hold_expire ON t_quota_hold (hold_status, expire_time);

-- 额度流水（只追加）：每次账户余额变动一行，带变动后三项余额快照，对账查询与日结对平依据
CREATE TABLE IF NOT EXISTS t_quota_flow (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id     BIGINT        NOT NULL,
    store_code     VARCHAR(32)   NOT NULL,
    hold_id        BIGINT,                                 -- 关联预占单（开户/调额流水为空）
    hold_no        VARCHAR(64),
    flow_type      VARCHAR(16)   NOT NULL,                 -- RESERVE/CONFIRM/RELEASE/EXPIRE/ADJUST
    amount         DECIMAL(14,2) NOT NULL,                 -- 变动金额（ADJUST 为总额度差额，可负；其余为正）
    total_after    DECIMAL(14,2),                          -- 变动后总额度
    reserved_after DECIMAL(14,2),                          -- 变动后占用中
    used_after     DECIMAL(14,2),                          -- 变动后已实扣
    oper_remark    VARCHAR(255),
    created_by     BIGINT,
    created_time   TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by     BIGINT,
    updated_time   TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    request_no     VARCHAR(64),
    biz_time       TIMESTAMP,
    version_no     BIGINT        NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_quota_flow_hold  ON t_quota_flow (hold_no);
CREATE INDEX IF NOT EXISTS idx_quota_flow_store ON t_quota_flow (store_code, flow_type);

-- 日结对平报告（运维数据）：每账户每日一行，重跑覆盖原行；
-- 全口径对平 BALANCED，任一不符 MISMATCH 并附差异明细
CREATE TABLE IF NOT EXISTS t_quota_recon (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recon_date              DATE          NOT NULL,        -- 对平日期（运行日）
    account_id              BIGINT        NOT NULL,
    store_code              VARCHAR(32)   NOT NULL,
    reserved_expected       DECIMAL(14,2),                 -- 应有占用 = 未结预占合计
    reserved_actual         DECIMAL(14,2),                 -- 实有占用 = 账户占用中
    used_expected           DECIMAL(14,2),                 -- 应有实扣 = 实扣流水合计
    used_actual             DECIMAL(14,2),                 -- 实有实扣 = 账户已实扣
    dangling_hold_count     INT           NOT NULL DEFAULT 0, -- 超时未还预占数（容忍扫描延迟后仍存在）
    confirm_without_reserve INT           NOT NULL DEFAULT 0, -- 无预占来源的实扣流水数（理论恒 0）
    recon_result            VARCHAR(16)   NOT NULL,        -- BALANCED / MISMATCH
    detail_json             CLOB,                          -- 差异明细（预占单号/流水号/差额）
    created_by              BIGINT,
    created_time            TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by              BIGINT,
    updated_time            TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    request_no              VARCHAR(64),
    biz_time                TIMESTAMP,
    version_no              BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT uk_quota_recon UNIQUE (account_id, recon_date)
);

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('quota-1', '门店额度三段式（预占/确认/释放）、只追加流水与日结对平');
